"""
Domain-dependent heuristic for the Lamps domain.

Bottleneck Analysis:
  Each "turn" flips a center cell and propagates flips in 4 directions.
  Every flip is a primitive action costing 1. Method precondition checks
  generated by the grounder also cost 1 each. The main serializing constraint
  is that each turn must be executed sequentially (play -> turn -> play -> ...),
  and each turn has overhead beyond just the flips.

Admissible Lower Bounds:
  Term 1 (goal_mismatch_count): Each cell that differs from its goal value must
    be flipped at least once (cost >= 1 per mismatched cell). This is admissible
    because no single flip action can fix two different cells.
  Term 2 (turn_structure_cost): Each turn in the task network requires at minimum
    the center flip (1 action) plus method precondition operators. We estimate
    a lower bound on remaining turns from the task network structure.
  Term 3 (min_turns_estimate): If there are mismatched cells, at least 1 turn
    is needed, and each turn has structural overhead from grounded methods.
"""

import time
from collections import defaultdict
from Pytrich.Heuristics.heuristic import Heuristic
from Pytrich.Search.htn_node import HTNNode
from Pytrich.model import Model


class LampsAnthropicOpus46Heuristic16(Heuristic):
    """
    Multi-component max heuristic for the Lamps domain.
    
    Uses goal mismatch counting and task network analysis to produce
    an admissible lower bound on remaining cost.
    """

    def __init__(self, lamps_anthropicopus46_heuristic_16=None, name="LampsAnthropicOpus46Heuristic16"):
        super().__init__(name=name)
        self.preprocessing_time = 0

        # Maps for fast state checking
        self.goal_on_facts = {}       # (x, y, s) -> global_id of fact +on[x,y,s]
        self.all_on_facts = {}        # (x, y, s) -> global_id
        self.goal_requirements = []   # list of (global_id, True/False) - what goal needs
        
        # For each cell (x,y), what status does the goal require?
        self.goal_cell_status = {}    # (x, y) -> required status 'Y' or 'N'
        
        # For each cell (x,y), the fact ids for on[x,y,Y] and on[x,y,N]
        self.cell_y_fact = {}         # (x, y) -> global_id of +on[x,y,Y]
        self.cell_n_fact = {}         # (x, y) -> global_id of +on[x,y,N]
        
        # All cells
        self.all_cells = set()
        
        # Task network analysis
        self.play_task_ids = set()    # global_ids of 'play' abstract tasks
        self.turn_task_ids = set()    # global_ids of 'turn' abstract tasks
        self.propagate_task_ids = set()  # global_ids of propagate_* tasks
        
        # Grid structure
        self.coords = set()
        self.next_map = {}            # coord -> next coord
        self.prev_map = {}            # coord -> prev coord
        self.min_coord = None
        self.max_coord = None
        self.grid_size = 0
        
        # Operator analysis
        self.flip_operator_ids = set()
        self.method_precondition_ids = set()
        self.min_overhead_per_turn = 0  # minimum method precondition ops per turn

    def initialize(self, model: Model, initial_node: HTNNode):
        start_time = time.time()
        self.model = model
        self._preprocess()
        self.preprocessing_time = time.time() - start_time
        h_value = self._compute(initial_node.state, initial_node.task_network)
        return super().initialize(model, h_value)

    def _parse_fact_name(self, name: str):
        name = name.strip()
        if name.startswith("+") or name.startswith("-"):
            name = name[1:]
            bracket_idx = name.find("[")
            if bracket_idx > 0 and name.endswith("]"):
                predicate = name[:bracket_idx]
                args_str = name[bracket_idx+1:-1]
                args = args_str.split(",") if args_str else []
                return predicate, args
        return None, []

    def _preprocess(self):
        """Parse all facts and build lookup structures."""
        
        # Build fact maps
        for fact in self.model.facts:
            predicate, args = self._parse_fact_name(fact.name)
            if predicate is None:
                continue
            
            if predicate == "on" and len(args) == 3:
                x, y, s = args[0], args[1], args[2]
                self.all_on_facts[(x, y, s)] = fact.global_id
                self.all_cells.add((x, y))
                self.coords.add(x)
                self.coords.add(y)
                if s == "Y":
                    self.cell_y_fact[(x, y)] = fact.global_id
                elif s == "N":
                    self.cell_n_fact[(x, y)] = fact.global_id
            elif predicate == "next" and len(args) == 2:
                self.next_map[args[0]] = args[1]
                self.prev_map[args[1]] = args[0]
            elif predicate == "max" and len(args) == 1:
                self.max_coord = args[0]
            elif predicate == "min" and len(args) == 1:
                self.min_coord = args[0]
        
        # Compute grid size
        self.grid_size = len(self.coords)
        
        # Extract goal requirements
        if hasattr(self.model, 'goals') and self.model.goals:
            goal_fact_names = self.model.state_explicit_repr(self.model.goals)
            for goal_name in goal_fact_names:
                predicate, args = self._parse_fact_name(goal_name)
                if predicate == "on" and len(args) == 3:
                    x, y, s = args[0], args[1], args[2]
                    self.goal_cell_status[(x, y)] = s
        
        # Build list of (global_id_to_check, expected_value) for goal checking
        # For each cell in goal, we check if its required status fact is true
        self.goal_checks = []
        for (x, y), s in self.goal_cell_status.items():
            if s == "Y" and (x, y) in self.cell_y_fact:
                self.goal_checks.append(self.cell_y_fact[(x, y)])
            elif s == "N" and (x, y) in self.cell_n_fact:
                self.goal_checks.append(self.cell_n_fact[(x, y)])
        
        # For mismatch counting, we need to know what fact to check
        # If goal says on(x,y,Y), then cell is mismatched if on[x,y,Y] is false
        self.mismatch_checks = []
        for (x, y), s in self.goal_cell_status.items():
            if s == "Y" and (x, y) in self.cell_y_fact:
                self.mismatch_checks.append(self.cell_y_fact[(x, y)])
            elif s == "N" and (x, y) in self.cell_n_fact:
                self.mismatch_checks.append(self.cell_n_fact[(x, y)])
        
        # Analyze abstract tasks
        for at in self.model.abstract_tasks:
            name_lower = at.name.lower()
            if 'play' in name_lower and 'propagate' not in name_lower:
                self.play_task_ids.add(at.global_id)
            elif 'turn' in name_lower and 'propagate' not in name_lower:
                self.turn_task_ids.add(at.global_id)
            elif 'propagate' in name_lower:
                self.propagate_task_ids.add(at.global_id)
        
        # Analyze operators
        for op in self.model.operators:
            name_lower = op.name.lower()
            if 'flip' in name_lower and '__method' not in name_lower:
                self.flip_operator_ids.add(op.global_id)
            elif '__method_precondition' in name_lower:
                self.method_precondition_ids.add(op.global_id)
        
        # Estimate minimum overhead per turn
        # A turn decomposes into: flip + propagate_up + propagate_down + propagate_left + propagate_right
        # Each propagate that ends immediately still has a method precondition check (cost 1)
        # The do_turn method itself may have a method precondition
        # Minimum: 1 flip + at least some method preconditions
        # From the grounding: do_turn has precondition checks, each propagate_*_end has precondition checks
        # Conservative estimate: at least 1 (flip) + method_precondition for do_turn
        # Let's count the minimum from decomposition structure
        self._estimate_turn_overhead()

    def _estimate_turn_overhead(self):
        """
        Estimate the minimum number of primitive operators per turn.
        
        A turn = flip(1) + propagate_up + propagate_down + propagate_left + propagate_right
        Each propagate in the best case (end immediately) costs at least 1 method_precondition op.
        The turn method itself may have a method_precondition op.
        
        We look at the decompositions to estimate this.
        """
        # Find turn decompositions
        min_turn_primitives = float('inf')
        for at in self.model.abstract_tasks:
            if at.global_id in self.turn_task_ids:
                for dec in at.decompositions:
                    # Count minimum primitives in this decomposition's task network
                    count = 0
                    for task in dec.task_network:
                        if hasattr(task, 'add_effects'):  # It's an operator
                            count += 1
                    # Each abstract task in the network will add at least something
                    # but we're being conservative
                    if count < min_turn_primitives:
                        min_turn_primitives = count
        
        if min_turn_primitives == float('inf'):
            min_turn_primitives = 1
        
        # Each propagate that terminates immediately costs at least 1 method_precondition
        # Find minimum cost for propagate tasks
        min_propagate_cost = float('inf')
        for at in self.model.abstract_tasks:
            if at.global_id in self.propagate_task_ids:
                for dec in at.decompositions:
                    cost = 0
                    for task in dec.task_network:
                        if hasattr(task, 'add_effects'):
                            cost += 1
                    if cost < min_propagate_cost:
                        min_propagate_cost = cost
        
        if min_propagate_cost == float('inf'):
            min_propagate_cost = 0
        
        # Minimum per turn: primitives from turn decomposition + 4 * min propagate cost
        # But the turn decomposition already includes the propagate tasks as abstract
        # So we estimate: min_turn_primitives (flip + maybe method_precondition) + 4 * min_propagate_cost
        self.min_overhead_per_turn = min_turn_primitives + 4 * min_propagate_cost
        
        # Also count play overhead
        self.min_play_overhead = 0
        for at in self.model.abstract_tasks:
            if at.global_id in self.play_task_ids:
                for dec in at.decompositions:
                    cost = 0
                    for task in dec.task_network:
                        if hasattr(task, 'add_effects'):
                            cost += 1
                    # do_play has subtasks: turn + play (both abstract)
                    # end_game has no subtasks
                    # The method precondition for do_play costs 1 if present
                    if cost > 0 and cost < 100:  # sanity check
                        self.min_play_overhead = max(self.min_play_overhead, 0)
                        # We'll use this as additional per-turn overhead
                        break

    def _count_mismatches(self, state_bitwise):
        """Count cells where current status differs from goal status."""
        count = 0
        for gid in self.mismatch_checks:
            if not ((state_bitwise >> gid) & 1):
                count += 1
        return count

    def _count_task_network_turns(self, task_network):
        """
        Count the minimum number of turns remaining in the task network.
        
        Each 'play' task can decompose into (turn + play) or empty.
        Each 'turn' task represents exactly one turn.
        """
        turn_count = 0
        play_count = 0
        propagate_count = 0
        operator_count = 0
        
        for task in task_network:
            gid = task.global_id
            if gid in self.turn_task_ids:
                turn_count += 1
            elif gid in self.play_task_ids:
                play_count += 1
            elif gid in self.propagate_task_ids:
                propagate_count += 1
            elif hasattr(task, 'add_effects'):  # primitive operator
                operator_count += 1
        
        return turn_count, play_count, propagate_count, operator_count

    def _compute(self, state_bitwise, task_network):
        """
        Compute heuristic as max of multiple admissible terms.
        """
        if not task_network:
            # No tasks remaining - if goal is met, h=0
            return 0
        
        mismatches = self._count_mismatches(state_bitwise)
        
        # Term 1: Each mismatched cell needs at least 1 flip action
        # This is admissible because each flip changes exactly one cell
        term1 = mismatches
        
        # Term 2: Task network analysis
        turn_count, play_count, propagate_count, operator_count = self._count_task_network_turns(task_network)
        
        # Each explicit turn in the task network costs at least 1 (the center flip)
        # plus method precondition overhead
        # Each propagate that's already expanded costs at least its method precondition
        term2 = operator_count  # Already-expanded primitive operators must be executed
        
        # Each turn task requires at least 1 flip
        term2 += turn_count  # At minimum 1 flip per turn
        
        # Each propagate needs at least its end method precondition (if any)
        # Being conservative: 0 for propagates since they might end empty
        
        # Term 3: Structural estimate
        # If there are mismatches, we need at least ceil(mismatches / max_flips_per_turn) turns
        # max_flips_per_turn is at most 1 + 4*(grid_size-1) = 4*grid_size - 3
        # But each turn costs at least min_overhead_per_turn
        if self.grid_size > 0:
            max_flips_per_turn = 1 + 4 * (self.grid_size - 1)
        else:
            max_flips_per_turn = 1
        
        if mismatches > 0 and max_flips_per_turn > 0:
            min_turns_needed = max(1, -(-mismatches // max_flips_per_turn))  # ceil division
            # But we can't have more turns than already committed
            if turn_count > 0:
                # turns are already in the network
                term3 = turn_count  # at least 1 flip each
            elif play_count > 0:
                # play can generate turns
                term3 = min_turns_needed
            else:
                term3 = 0
        else:
            term3 = 0
        
        # Term 4: More refined per-cell analysis
        # Look at which cells need flipping and estimate if they can be covered
        # by propagation from a single turn
        # For now, use the mismatch count as the primary signal
        
        # Term 5: Account for method preconditions in task network
        # Each method application that has a precondition generates a __method_precondition operator
        # These cost 1 each
        # For each turn: do_turn method has precondition -> 1 op
        # For each propagate end: has precondition -> 1 op each
        # Minimum: per turn, 4 propagate ends (each with method precondition) = 4 ops
        # Plus do_turn method precondition = 1 op
        # Plus flip = 1 op
        # Total minimum per turn: ~6 ops
        
        # But we need to be careful about admissibility
        # Let's count method_precondition operators already in the task network
        method_prec_in_tn = 0
        for task in task_network:
            if hasattr(task, 'add_effects'):  # primitive
                if hasattr(task, 'name') and '__method_precondition' in task.name.lower():
                    method_prec_in_tn += 1
        
        # The existing operators in task network are definite costs
        definite_cost = operator_count
        
        # For each turn task, minimum cost includes flip + propagate overhead
        # Being conservative: each turn costs at least 1 flip
        # Each propagate that ends costs 1 method_precondition typically
        # So per turn: 1 flip + 4 * 1 method_precondition = 5
        # But let's verify with min_overhead_per_turn
        per_turn_min = max(1, self.min_overhead_per_turn)
        
        term5 = definite_cost + turn_count * per_turn_min
        
        # For play tasks, if mismatches exist, at least one more turn is needed
        if play_count > 0 and mismatches > 0 and turn_count == 0:
            term5 += per_turn_min  # At least one turn from play
        
        h = max(term1, term2, term3, term5)
        
        return h

    def __call__(self, parent_node: HTNNode, node: HTNNode) -> float:
        h_value = self._compute(node.state, node.task_network)
        super().update_info(h_value)
        return h_value

    def __repr__(self):
        return f"LampsAnthropicOpus46Heuristic16(grid={self.grid_size})"

    def __str__(self):
        return f"LampsAnthropicOpus46Heuristic16 with grid size {self.grid_size}"

    def __output__(self):
        return (
            f"Lamps Heuristic Info:\n"
            f"\tName: {self.name}\n"
            f"\tGrid Size: {self.grid_size}\n"
            f"\tGoal Cells: {len(self.goal_cell_status)}\n"
            f"\tMin Overhead Per Turn: {self.min_overhead_per_turn}\n"
            f"\tPreprocessing Time: {self.preprocessing_time:.4f}s\n"
            f"\tTotal Calls: {self.calls}\n"
            f"\tMin H-Value: {self.min_hvalue}\n"
        )
