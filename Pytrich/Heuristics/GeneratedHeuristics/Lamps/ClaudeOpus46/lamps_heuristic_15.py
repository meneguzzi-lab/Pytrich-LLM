"""
Domain-dependent heuristic for the Lamps domain.

Bottleneck: Each cell that differs from goal must be flipped at least once (cost 1 each).
A "turn" flips a center cell and propagates along 4 directions, flipping chains of
same-status neighbors. Each turn costs at least 1 (the center flip) plus method
precondition operators generated by the grounder.

Admissible lower bounds:
1. Cell-diff bound: Count cells differing from goal. Each differing cell needs at least
   one flip action (cost 1). Multiple cells can be flipped in one turn, but each flip
   is still a separate primitive action costing 1. So #differing_cells is admissible.
2. Turn-count bound: Each turn in the task network requires at least 1 flip + method
   precondition operators. We count remaining abstract tasks that represent turns.
3. Task-network bound: Count primitive operators and estimate abstract task costs from
   the current task network.
"""

import time
from collections import defaultdict
from Pytrich.Heuristics.heuristic import Heuristic
from Pytrich.Search.htn_node import HTNNode
from Pytrich.model import Model


class LampsAnthropicOpus46Heuristic15(Heuristic):
    """
    Heuristic for Lamps domain.
    
    Uses max of:
    - Number of cells that differ from goal state (each needs >= 1 flip action)
    - Task-network-based estimate considering method precondition overhead
    """

    def __init__(self, lamps_anthropicopus46_heuristic_15=None, name="LampsAnthropicOpus46Heuristic15"):
        super().__init__(name=name)
        self.preprocessing_time = 0
        
        # Maps for fast lookup
        self.on_facts = {}          # (x, y, s) -> fact.global_id
        self.goal_config = {}       # (x, y) -> desired status ('Y' or 'N')
        self.all_cells = set()      # set of (x, y) tuples
        
        # For each cell, store fact ids for both statuses
        self.cell_y_fact = {}       # (x, y) -> global_id of on[x,y,Y]
        self.cell_n_fact = {}       # (x, y) -> global_id of on[x,y,N]
        
        # Grid structure
        self.next_map = {}          # coord -> next coord
        self.prev_map = {}          # coord -> prev coord
        self.max_coords = set()
        self.min_coords = set()
        self.coords = set()
        
        # Status object names
        self.status_y = None
        self.status_n = None
        
        # Task type identification
        self.turn_task_ids = set()      # global_ids of abstract tasks that are 'turn'
        self.play_task_ids = set()      # global_ids of abstract tasks that are 'play'
        self.propagate_task_ids = set() # global_ids for propagate tasks
        self.flip_op_ids = set()        # global_ids of flip operators
        self.method_precondition_op_ids = set()  # global_ids of __method_precondition operators
        
        # For estimating per-turn overhead
        self.min_turn_cost = 1  # At minimum a turn costs 1 flip
        
    def initialize(self, model: Model, initial_node: HTNNode):
        start_time = time.time()
        self.model = model
        
        self._preprocess()
        
        self.preprocessing_time = time.time() - start_time
        
        h_value = self._compute(initial_node.state, initial_node.task_network)
        return super().initialize(model, h_value)
    
    def _parse_fact_name(self, name: str):
        name = name.strip()
        if name.startswith("+") or name.startswith("-"):
            name = name[1:]
            bracket_idx = name.find("[")
            if bracket_idx > 0 and name.endswith("]"):
                predicate = name[:bracket_idx]
                args_str = name[bracket_idx+1:-1]
                args = args_str.split(",") if args_str else []
                return predicate, args
        return None, []
    
    def _preprocess(self):
        """Extract domain structure from grounded facts and build lookup maps."""
        
        # Parse all facts
        for fact in self.model.facts:
            predicate, args = self._parse_fact_name(fact.name)
            if predicate is None:
                continue
            
            if predicate == "on" and len(args) == 3:
                x, y, s = args[0], args[1], args[2]
                self.on_facts[(x, y, s)] = fact.global_id
                self.all_cells.add((x, y))
                self.coords.add(x)
                self.coords.add(y)
                
                # Identify Y and N status names
                if s.upper() == 'Y' or s.endswith('Y') or 'Y' in s.upper():
                    self.cell_y_fact[(x, y)] = fact.global_id
                if s.upper() == 'N' or s.endswith('N') or 'N' in s.upper():
                    self.cell_n_fact[(x, y)] = fact.global_id
                    
            elif predicate == "next" and len(args) == 2:
                self.next_map[args[0]] = args[1]
                self.prev_map[args[1]] = args[0]
                
            elif predicate == "max" and len(args) == 1:
                self.max_coords.add(args[0])
                
            elif predicate == "min" and len(args) == 1:
                self.min_coords.add(args[0])
        
        # Extract goal configuration
        if hasattr(self.model, 'goals') and self.model.goals:
            goal_fact_names = self.model.state_explicit_repr(self.model.goals)
            for goal_name in goal_fact_names:
                predicate, args = self._parse_fact_name(goal_name)
                if predicate == "on" and len(args) == 3:
                    x, y, s = args[0], args[1], args[2]
                    self.goal_config[(x, y)] = s
        
        # Identify status names from facts
        statuses = set()
        for (x, y, s) in self.on_facts:
            statuses.add(s)
        
        # Usually two statuses; identify them
        # We'll store per-cell, per-status fact ids
        self.status_list = sorted(statuses)
        self.cell_status_fact = {}  # (x, y, status_str) -> global_id
        for (x, y, s), gid in self.on_facts.items():
            self.cell_status_fact[(x, y, s)] = gid
        
        # Identify abstract task types
        for at in self.model.abstract_tasks:
            name_lower = at.name.lower()
            if 'turn' in name_lower and 'propagate' not in name_lower and 'play' not in name_lower:
                self.turn_task_ids.add(at.global_id)
            elif 'play' in name_lower:
                self.play_task_ids.add(at.global_id)
            elif 'propagate' in name_lower:
                self.propagate_task_ids.add(at.global_id)
        
        # Identify operator types
        for op in self.model.operators:
            name_lower = op.name.lower()
            if 'flip' in name_lower and '__method_precondition' not in name_lower:
                self.flip_op_ids.add(op.global_id)
            elif '__method_precondition' in name_lower:
                self.method_precondition_op_ids.add(op.global_id)
        
        # Estimate minimum cost per turn:
        # A turn = flip(center) + propagate_up + propagate_down + propagate_left + propagate_right
        # The do_turn method has a method_precondition check (1 action)
        # + flip (1 action) + 4 propagation tasks
        # Each propagation task ends with either end_field or end_different (each has a method_precondition = 1)
        # or do (method_precondition + flip + recursive)
        # Minimum turn: method_prec(do_turn) + flip + 4 * method_prec(propagate_end) = 1 + 1 + 4 = 6
        # But let's count more carefully from the decomposition structure
        self.min_turn_overhead = self._estimate_min_turn_cost()
    
    def _estimate_min_turn_cost(self):
        """
        Estimate minimum cost of a single turn.
        
        A turn decomposes to:
        - do_turn method: has method_precondition (cost 1 if present)
          - flip action (cost 1)
          - propagate_up (minimum: end method with method_precondition cost 1)
          - propagate_down (minimum: end method with method_precondition cost 1)
          - propagate_left (minimum: end method with method_precondition cost 1)
          - propagate_right (minimum: end method with method_precondition cost 1)
        
        Minimum total = 1 (method_prec for do_turn) + 1 (flip) + 4 * 1 (propagation ends) = 6
        But we need to check if method_preconditions are actually generated.
        """
        # Check if turn tasks have decompositions with method preconditions
        min_cost = 1  # At least the flip
        
        # Look at turn decompositions
        for at in self.model.abstract_tasks:
            if at.global_id in self.turn_task_ids:
                for decomp in at.decompositions:
                    # Count operators in task network
                    op_count = 0
                    for task in decomp.task_network:
                        if hasattr(task, 'cost'):  # It's an operator
                            op_count += 1
                    if op_count > 0:
                        min_cost = max(min_cost, op_count)
                break
        
        # Check propagation minimum cost
        min_prop_cost = 0
        for at in self.model.abstract_tasks:
            if at.global_id in self.propagate_task_ids:
                for decomp in at.decompositions:
                    # End methods have 0 or 1 operators (method precondition)
                    op_count = 0
                    has_abstract = False
                    for task in decomp.task_network:
                        if hasattr(task, 'cost'):
                            op_count += 1
                        elif hasattr(task, 'decompositions'):
                            has_abstract = True
                    if not has_abstract:  # This is an end method
                        min_prop_cost = max(min_prop_cost, op_count)
                        break
                break
        
        return min_cost + 4 * min_prop_cost
    
    def _count_differing_cells(self, state_bitwise):
        """
        Count cells that differ from goal configuration.
        Each differing cell requires at least one flip action (cost 1).
        This is admissible.
        """
        diff_count = 0
        for (x, y), goal_status in self.goal_config.items():
            fact_id = self.cell_status_fact.get((x, y, goal_status))
            if fact_id is not None:
                if not ((state_bitwise >> fact_id) & 1):
                    diff_count += 1
        return diff_count
    
    def _count_turns_in_network(self, task_network):
        """
        Count the minimum number of turns remaining in the task network.
        Each turn requires at least min_turn_overhead primitive actions.
        
        For play tasks, we estimate based on remaining differences.
        """
        turn_count = 0
        play_count = 0
        propagate_count = 0
        operator_count = 0
        
        for task in task_network:
            gid = task.global_id
            if gid in self.turn_task_ids:
                turn_count += 1
            elif gid in self.play_task_ids:
                play_count += 1
            elif gid in self.propagate_task_ids:
                propagate_count += 1
            elif hasattr(task, 'cost'):  # operator
                operator_count += 1
        
        return turn_count, play_count, propagate_count, operator_count
    
    def _estimate_propagation_flips(self, state_bitwise):
        """
        For cells that differ from goal, estimate how many are in runs
        that could be flipped together in a single propagation.
        This helps estimate the number of turns needed.
        
        Returns estimated minimum number of turns to fix all differences.
        """
        if not self.goal_config:
            return 0
        
        diff_count = 0
        for (x, y), goal_status in self.goal_config.items():
            fact_id = self.cell_status_fact.get((x, y, goal_status))
            if fact_id is not None:
                if not ((state_bitwise >> fact_id) & 1):
                    diff_count += 1
        
        return diff_count
    
    def _compute(self, state_bitwise, task_network):
        """
        Compute heuristic value as max of multiple admissible terms.
        """
        # Term 1: Number of differing cells
        # Each differing cell needs at least 1 flip action (cost 1)
        # This is admissible because even if multiple flips happen in one turn,
        # each flip is a separate primitive action with cost 1.
        diff_count = self._count_differing_cells(state_bitwise)
        
        # Term 2: Task network based estimate
        turn_count, play_count, propagate_count, operator_count = \
            self._count_turns_in_network(task_network)
        
        # Each explicit turn in the network costs at least 1 (the center flip)
        # Plus each propagation task costs at least 0 (if it ends immediately)
        # But method preconditions add cost
        task_estimate = operator_count  # primitive operators in network
        
        # For turn tasks already in the network, they need at least 1 flip each
        task_estimate += turn_count  # at minimum 1 flip per turn
        
        # For propagate tasks, they need at least 0 flips (could end immediately)
        # but they have method precondition overhead - let's count that
        # Each propagation end has a method_precondition operator (cost 1) if grounder adds them
        # We'll be conservative and not count these for admissibility
        
        # For play tasks, they might decompose to (turn, play) or empty
        # The minimum decomposition is empty (end_game), cost 0
        # But if there are differences, at least some turns are needed
        if play_count > 0 and diff_count > 0:
            # We need at least enough turns to flip all differing cells
            # In the best case, one turn can flip many cells (a cross pattern)
            # But each flip is still cost 1, so diff_count is already captured in term 1
            # The play task overhead: each turn needs method preconditions
            # Minimum turns needed: at least 1 for each isolated differing cell
            # that can't be reached by propagation from another cell's turn
            pass
        
        # Term 3: Combined estimate considering turn overhead
        # Each turn that must happen costs at least min_turn_overhead
        # But we need to estimate how many turns are needed
        # Lower bound on turns needed: we can't do better than
        # max(1, ceil(diff_count / max_flips_per_turn))
        # But max_flips_per_turn depends on grid size
        # Conservative: at least 1 turn needed if any diffs exist
        
        # More refined: count "change groups"
        # A turn at (x,y) flips (x,y) and then propagates in 4 directions
        # flipping same-status neighbors. The propagation changes cells that
        # have the SAME status as the original cell had BEFORE the flip.
        # So a turn can fix multiple cells if they form a cross pattern
        # centered at (x,y) with matching status.
        
        # For the heuristic, diff_count is our strongest admissible term.
        # Let's also add method precondition costs.
        
        # Each turn decomposition, in practice after grounding, generates:
        # __method_precondition for do_turn + flip + 4 propagation tasks
        # Each propagation task generates at least 1 __method_precondition (for the end check)
        # So minimum per turn ≈ 1 (method_prec) + 1 (flip) + 4 * 1 (end method_precs) = 6
        # But we don't know exactly, so let's be conservative
        
        # Estimate overhead: for each explicit turn in network, add overhead
        turn_overhead_estimate = 0
        if turn_count > 0:
            turn_overhead_estimate = turn_count  # At least 1 per turn for the flip
        
        # Propagation estimate: each propagate task has at least 1 method_prec
        prop_overhead = 0  # Be conservative
        
        # Final terms
        term1 = diff_count  # Admissible: each diff needs >= 1 flip
        term2 = task_estimate  # Admissible: explicit operators + minimum per turn
        
        # Additional refinement: if there are differences and play tasks,
        # each turn has overhead beyond just flips
        # Minimum turns * minimum overhead per turn
        if play_count > 0 and diff_count > 0:
            # Need at least 1 turn, which means at least diff_count flips
            # But also method_precondition overhead per turn
            # We don't know exact number of turns, but diff_count covers flip costs
            # Let's try to estimate minimum turns needed
            n_coords = len(self.coords)
            if n_coords > 0:
                # A single turn can flip at most 1 + 4*(n-1) = 4n-3 cells
                # (center + 4 directions each up to n-1 cells)
                max_flips_per_turn = 1 + 4 * (n_coords - 1) if n_coords > 1 else 1
                # But in practice, propagation only flips same-status consecutive cells
                # More realistic max: depends on board state
                # Conservative: assume each turn can fix all diffs (best case)
                min_turns_needed = 1 if diff_count > 0 else 0
            else:
                min_turns_needed = diff_count
        else:
            min_turns_needed = 0
        
        # Term 3: turns already committed in network * overhead
        # For committed turns (already in task network), count minimum primitive actions
        committed_cost = operator_count
        for task in task_network:
            gid = task.global_id
            if gid in self.turn_task_ids:
                committed_cost += 1  # minimum flip
        
        h_value = max(term1, term2, committed_cost)
        
        return h_value
    
    def __call__(self, parent_node: HTNNode, node: HTNNode) -> float:
        h_value = self._compute(node.state, node.task_network)
        super().update_info(h_value)
        return h_value
    
    def __repr__(self):
        return f"LampsAnthropicOpus46Heuristic15(cells={len(self.all_cells)}, goals={len(self.goal_config)})"
    
    def __str__(self):
        return f"LampsAnthropicOpus46Heuristic15 with {len(self.all_cells)} cells"
    
    def __output__(self):
        return (
            f"Lamps Heuristic Info:\n"
            f"\tName: {self.name}\n"
            f"\tCells: {len(self.all_cells)}\n"
            f"\tGoal Config Size: {len(self.goal_config)}\n"
            f"\tCoords: {len(self.coords)}\n"
            f"\tPreprocessing Time: {self.preprocessing_time:.4f}s\n"
            f"\tTotal Calls: {self.calls}\n"
            f"\tMin H-Value: {self.min_hvalue}\n"
        )
