"""
Domain-dependent heuristic for the Lamps domain.

Bottleneck: Each cell that differs from the goal must be flipped at least once
(costing 1 primitive action per flip). Turns also incur overhead from
__method_precondition_* operators generated by the grounder.

Admissible lower bounds:
  Term 1 (mismatch count): Each cell differing from goal needs >= 1 flip action.
    This is admissible because no single flip action can change more than one cell.
  Term 2 (turn-based lower bound): If there are k mismatched cells, we need at
    least some number of turns. Each turn has overhead (method precondition ops).
    We estimate a per-turn minimum cost and multiply.
  Term 3 (task network awareness): Remaining compound tasks in the network
    provide structural lower bounds on remaining actions.
"""

import time
from collections import defaultdict
from Pytrich.Heuristics.heuristic import Heuristic
from Pytrich.Search.htn_node import HTNNode
from Pytrich.model import Model


class LampsAnthropicOpus46Heuristic14(Heuristic):
    """
    Heuristic for the Lamps domain based on counting mismatched cells
    relative to the goal state, combined with task network analysis.
    
    Each cell that differs from goal requires at least one flip action (cost 1).
    This provides a tight admissible lower bound.
    """

    def __init__(self, lamps_anthropicopus46_heuristic_14=None, name="LampsAnthropicOpus46Heuristic14"):
        super().__init__(name=name)
        self.preprocessing_time = 0

        # Maps for efficient state checking
        self.goal_on_facts = {}       # (x, y, s) -> fact.global_id
        self.on_facts = {}            # (x, y, s) -> fact.global_id
        self.on_facts_by_cell = {}    # (x, y) -> list of (status, fact) 
        
        # Goal information
        self.goal_cells = {}          # (x, y) -> required status
        self.goal_fact_ids = []       # list of global_ids that must be true in goal
        
        # All cells
        self.all_cells = set()
        self.all_coords = set()
        
        # Precomputed goal bitmask for fast comparison
        self.goal_bitmask = 0
        self.goal_relevant_mask = 0   # mask of bits that matter for goal
        
        # For task network analysis
        self.play_task_ids = set()
        self.turn_task_ids = set()
        self.propagate_task_ids = set()
        self.flip_op_ids = set()
        self.method_precondition_ids = set()
        
        # Track per-cell fact ids for fast lookup
        self.cell_y_fact = {}  # (x,y) -> global_id of on[x,y,Y]
        self.cell_n_fact = {}  # (x,y) -> global_id of on[x,y,N]

    def _parse_fact_name(self, name: str):
        """Parse a grounded fact name into (predicate, args)."""
        name = name.strip()
        if name.startswith("+") or name.startswith("-"):
            name = name[1:]
            bracket_idx = name.find("[")
            if bracket_idx > 0 and name.endswith("]"):
                predicate = name[:bracket_idx]
                args_str = name[bracket_idx+1:-1]
                args = args_str.split(",") if args_str else []
                return predicate, args
        elif name.startswith("(") and name.endswith(")"):
            inner = name[1:-1]
            parts = inner.split()
            if parts:
                return parts[0], parts[1:]
        return None, []

    def initialize(self, model: Model, initial_node: HTNNode):
        """Preprocess domain structure for fast heuristic computation."""
        start_time = time.time()
        self.model = model

        self._preprocess()

        self.preprocessing_time = time.time() - start_time

        h_value = self._compute(initial_node.state, initial_node.task_network)
        return super().initialize(model, h_value)

    def _preprocess(self):
        """Extract domain structure from grounded facts and operators."""
        
        # Parse all facts to find on[x,y,s] facts
        for fact in self.model.facts:
            predicate, args = self._parse_fact_name(fact.name)
            if predicate is None:
                continue
            
            if predicate == "on" and len(args) == 3:
                x, y, s = args[0], args[1], args[2]
                self.on_facts[(x, y, s)] = fact.global_id
                self.all_cells.add((x, y))
                self.all_coords.add(x)
                self.all_coords.add(y)
                
                if (x, y) not in self.on_facts_by_cell:
                    self.on_facts_by_cell[(x, y)] = []
                self.on_facts_by_cell[(x, y)].append((s, fact))
                
                if s == "Y":
                    self.cell_y_fact[(x, y)] = fact.global_id
                elif s == "N":
                    self.cell_n_fact[(x, y)] = fact.global_id
        
        # Parse goal state
        if hasattr(self.model, 'goals') and self.model.goals:
            goal_fact_names = self.model.state_explicit_repr(self.model.goals)
            for goal_name in goal_fact_names:
                predicate, args = self._parse_fact_name(goal_name)
                if predicate == "on" and len(args) == 3:
                    x, y, s = args[0], args[1], args[2]
                    self.goal_cells[(x, y)] = s
            
            self.goal_bitmask = self.model.goals
        
        # Build list of goal fact global_ids for fast checking
        for (x, y), s in self.goal_cells.items():
            key = (x, y, s)
            if key in self.on_facts:
                self.goal_fact_ids.append(self.on_facts[key])
        
        # Parse operators to identify flip ops and method precondition ops
        for op in self.model.operators:
            op_name = op.name.lower() if op.name else ""
            if "flip" in op_name and "method" not in op_name:
                self.flip_op_ids.add(op.global_id)
            elif "__method_precondition" in op_name or "method_precondition" in op_name:
                self.method_precondition_ids.add(op.global_id)
        
        # Parse abstract tasks
        for at in self.model.abstract_tasks:
            at_name = at.name.lower() if at.name else ""
            if "play" in at_name:
                self.play_task_ids.add(at.global_id)
            elif "turn" in at_name and "propagate" not in at_name:
                self.turn_task_ids.add(at.global_id)
            elif "propagate" in at_name:
                self.propagate_task_ids.add(at.global_id)

    def _count_mismatched_cells(self, state: int) -> int:
        """
        Count cells where current status differs from goal status.
        Each mismatch requires at least 1 flip action.
        Uses fast bitwise checks.
        """
        mismatches = 0
        for (x, y), goal_status in self.goal_cells.items():
            if goal_status == "Y":
                # Goal wants Y. Check if on[x,y,Y] is true.
                fid = self.cell_y_fact.get((x, y))
                if fid is not None:
                    if not ((state >> fid) & 1):
                        mismatches += 1
                else:
                    mismatches += 1
            elif goal_status == "N":
                # Goal wants N. Check if on[x,y,N] is true.
                fid = self.cell_n_fact.get((x, y))
                if fid is not None:
                    if not ((state >> fid) & 1):
                        mismatches += 1
                else:
                    mismatches += 1
        return mismatches

    def _task_network_lower_bound(self, task_network) -> int:
        """
        Estimate minimum primitive actions from the task network structure.
        
        Each 'turn' task decomposes to at least 1 flip action + method precondition ops.
        Each 'play' task that will eventually decompose to turns adds cost.
        Propagate tasks may or may not produce flips depending on state.
        
        We provide a lower bound: each operator/primitive in the network costs 1.
        Each turn abstract task costs at least 1 (the center flip) + method precondition costs.
        """
        if not task_network:
            return 0
        
        primitive_count = 0
        turn_count = 0
        propagate_count = 0
        play_count = 0
        
        for task in task_network:
            gid = task.global_id
            if gid in self.turn_task_ids:
                turn_count += 1
            elif gid in self.play_task_ids:
                play_count += 1
            elif gid in self.propagate_task_ids:
                # Propagate tasks may produce 0 or more flips
                # Lower bound is 0 (they can end immediately)
                pass
            elif gid <= self.model.iop_end and gid >= self.model.iop_init:
                # This is a primitive operator - costs 1
                primitive_count += 1
        
        # Each turn requires at least 1 flip + 1 method precondition check
        # The do_turn method has: flip + propagate_up + propagate_down + propagate_left + propagate_right
        # flip costs 1, each propagate may cost 0+
        # But do_turn also has a method precondition operator costing 1
        turn_lower = turn_count * 2  # At least: 1 method_precondition + 1 flip per turn
        
        return primitive_count + turn_lower

    def _compute(self, state: int, task_network) -> float:
        """
        Compute heuristic value combining multiple admissible terms.
        """
        # If no goal cells defined, return 0
        if not self.goal_cells:
            return 0
        
        # Term 1: Direct mismatch count
        # Each mismatched cell needs at least 1 flip action (cost 1)
        mismatches = self._count_mismatched_cells(state)
        
        if mismatches == 0 and (not task_network or len(task_network) == 0):
            return 0
        
        # Term 2: Task network structural lower bound
        tn_bound = self._task_network_lower_bound(task_network)
        
        # Term 3: Turn-based lower bound
        # If there are mismatches, we need at least 1 turn.
        # Each turn involves: at minimum 1 method_precondition + 1 flip = 2 ops.
        # But a turn can fix multiple cells via propagation.
        # However in the worst case each turn fixes only 1 cell.
        # A single turn's flip + propagation can fix at most:
        #   1 (center) + up to (n-1) in each of 4 directions = 1 + 4*(n-1)
        # But typically much less. 
        # Conservative: each turn fixes at most grid_size cells in the best case.
        # So minimum turns >= ceil(mismatches / max_cells_per_turn)
        # But we also know each turn costs at least 2 (method_precondition + flip)
        # So turn_bound >= ceil(mismatches / max_per_turn) * 2
        
        # Actually, the simplest admissible bound: mismatches itself.
        # Each flip action changes exactly 1 cell. So we need at least 'mismatches' flip actions.
        # Each flip action costs 1. So mismatches is a valid lower bound on total flip cost.
        # But there's additional overhead from method_precondition operators.
        
        # If mismatches > 0, we need at least 1 turn, which means:
        # do_play decomposes to (turn, play), and turn needs method_precondition + flip
        # Also do_play itself may have a method_precondition
        # play -> end_game also has a (possibly free) decomposition
        
        # Be conservative: just use mismatches as the flip lower bound
        # Plus: if mismatches > 0, at least 1 turn overhead
        
        turn_overhead = 0
        if mismatches > 0:
            # We need at least 1 turn, each turn has method_precondition overhead
            # Estimate minimum number of turns needed
            # Each turn can propagate and flip multiple cells, but
            # the center flip always happens. Propagation only flips cells
            # that have the SAME status as the old status of center.
            # This is complex to compute, so be conservative.
            # At minimum we need ceil(mismatches / max_propagation_reach) turns
            # max_propagation_reach could be up to 4*(n-1)+1 for grid size n
            n = len(self.all_coords) if self.all_coords else 1
            max_per_turn = 1 + 4 * (n - 1)  # theoretical max cells changed per turn
            min_turns = max(1, (mismatches + max_per_turn - 1) // max_per_turn)
            # Each turn adds at least 1 method_precondition op overhead
            turn_overhead = min_turns  # 1 extra op per turn for method_precondition
        
        # Combine: take max of independent bounds
        h_mismatch = mismatches + turn_overhead
        h_tn = tn_bound
        
        h_value = max(h_mismatch, h_tn)
        
        return float(h_value)

    def __call__(self, parent_node: HTNNode, node: HTNNode) -> float:
        """Calculate heuristic for search node."""
        h_value = self._compute(node.state, node.task_network)
        super().update_info(h_value)
        return h_value

    def __repr__(self):
        return f"LampsAnthropicOpus46Heuristic14(cells={len(self.all_cells)})"

    def __str__(self):
        return f"LampsAnthropicOpus46Heuristic14 with {len(self.all_cells)} cells"

    def __output__(self):
        return (
            f"Lamps Heuristic Info:\n"
            f"\tName: {self.name}\n"
            f"\tCells: {len(self.all_cells)}\n"
            f"\tGoal cells: {len(self.goal_cells)}\n"
            f"\tCoords: {len(self.all_coords)}\n"
            f"\tPreprocessing Time: {self.preprocessing_time:.4f}s\n"
            f"\tTotal Calls: {self.calls}\n"
            f"\tMin H-Value: {self.min_hvalue}\n"
        )
