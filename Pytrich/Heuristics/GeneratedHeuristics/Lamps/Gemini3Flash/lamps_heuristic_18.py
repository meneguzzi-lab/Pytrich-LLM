from Pytrich.Heuristics.heuristic import Heuristic
from Pytrich.Search.htn_node import HTNNode
from Pytrich.model import Model

"""
Domain-Dependent Heuristic for Lamps Domain

1. Bottleneck Identification:
   The bottleneck in the Lamps domain is the total number of status toggles required. 
   Every coordinate whose current status (on ?x ?y ?s) does not match the goal status 
   must be flipped at least once. Since the 'flip' action is a primitive action 
   with a cost of 1, the number of mismatches is a strict lower bound on the path cost.

2. Admissible Lower Bounds:
   - Term 1 (State-based): Hamming distance between the current state and the goal 
     state regarding the 'on' predicate. Each mismatch (goal fact not in current state) 
     requires at least one primitive 'flip' action. Admissible because one flip action 
     at most satisfies one goal mismatch.
   - Term 2 (Task-based): The count of primitive operators already present in the 
     task network. Since Pytrich charges 1 for every primitive operator, and these 
     operators MUST be executed to empty the network, their cost is unavoidable.

3. Preprocessing:
   Goal bits are accessed directly from the model.goals integer for high-performance 
   bitwise comparison in the evaluation function.

4. Combination:
   We use max(Term 1, Term 2) to maintain admissibility while capturing progress from 
   both the state status and the committed task pipeline.
"""

class LampsGemini3FlashHeuristic18(Heuristic):
    def __init__(self, lamps_gemini3flash_heuristic_18=None, name="LampsGemini3FlashHeuristic18"):
        super().__init__(name=name)
        self.lamps_gemini3flash_heuristic_18 = lamps_gemini3flash_heuristic_18

    def initialize(self, model: Model, initial_node: HTNNode):
        """
        Called once before search starts. We set up access to the model goals.
        """
        self.model = model
        
        # Compute the initial heuristic value
        h_value = self._compute(initial_node.state, initial_node.task_network)
        
        return super().initialize(model, h_value)

    def _compute(self, state: int, task_network: list) -> float:
        """
        Efficiently calculate the heuristic value using bitwise operations and TN inspection.
        """
        # 1. Hamming Distance to Goal (Mismatches)
        # We count bits that are 1 in model.goals but 0 in state
        # Python's ~state is -(state+1). Using (goals & ~state) correctly isolates bits 
        # that are required by the goal but missing in the state.
        mismatches_mask = self.model.goals & ~state
        # bin().count('1') is highly optimized in Python for counting set bits
        h_state = bin(mismatches_mask).count('1')

        # 2. Minimum Cost of Committed Primitive Actions
        # Every Operator in the task network has a .cost (typically 1).
        # Abstract tasks have no cost themselves, though their decompositions do.
        h_tn = 0
        for task in task_network:
            # Check if it is an instance of Operator (primitive)
            # and add its cost (including __method_precondition operators).
            if hasattr(task, 'cost'):
                h_tn += task.cost

        # Return max to maintain admissibility.
        # If the number of mismatches is greater than the current pipeline, 
        # it means more turns/flips must be generated by decomposing current tasks.
        # If the pipeline cost is higher, it means we have already committed to a 
        # sequence of actions longer than the bare minimum mismatch count.
        return float(max(h_state, h_tn))

    def __call__(self, parent_node: HTNNode, node: HTNNode) -> float:
        """
        Evaluates the heuristic for each node expansion.
        """
        h_value = self._compute(node.state, node.task_network)
        super().update_info(h_value)
        return h_value

    def __repr__(self):
        return f"LampsGemini3FlashHeuristic18(calls={self.calls})"

    def __str__(self):
        return "LampsGemini3FlashHeuristic18"
