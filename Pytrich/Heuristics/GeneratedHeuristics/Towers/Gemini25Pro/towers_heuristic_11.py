import math
import time
from Pytrich.Heuristics.heuristic import Heuristic
from Pytrich.Search.htn_node import HTNNode
from Pytrich.model import Model

class TowersGemini25ProHeuristic11(Heuristic):
    """
    A domain-dependent heuristic for the Towers of Hanoi domain.

    This heuristic estimates the cost to complete a task based on the hierarchical
    structure of the problem. The core idea is that the cost of moving a tower of
    k rings is 2^k - 1. By inspecting the parameters of the method being
    decomposed, we can determine the size 'k' of the subproblem and apply this
    formula to get a highly accurate, admissible heuristic value.

    Design Rationale:
    1.  **Domain Insight**: The Towers of Hanoi problem has an optimal substructure
        with a well-known exponential cost function related to the number of rings.
        This heuristic directly leverages this knowledge.
    2.  **Hierarchical Analysis**: The heuristic value is not based on the flat
        state but on the method being used in the HTN decomposition. This aligns
        with the hierarchical nature of the problem.
    3.  **Parameter-Aware**: It parses the grounded method names to extract ring
        parameters (e.g., 'r5'). This allows it to determine the scale of the
        subproblem (e.g., a 5-ring problem).
    4.  **Cost Estimation**:
        - For high-level tasks like 'shiftTower' or 'selectDirection' that initiate
          a k-ring subproblem, the heuristic value is set to the exact cost: 2^k - 1.
        - For recursive sub-methods like 'exchangeLR', which involve one move and a
          recursive call for k-1 rings, the heuristic estimates the cost of the
          sub-plan generated by that method, which is 2^(k-1).
        - For base cases ('exchangeClear') and primitive actions ('move_abstract'),
          the cost is 0 and 1, respectively.
        - For methods where the ring size cannot be determined from parameters (like
          'm-rotateTower'), a conservative, small constant value is returned to
          ensure admissibility.
    5.  **Admissibility**: The heuristic provides the exact cost of optimally solving
        the sub-plan rooted at the current method decomposition. Since this is the
        true minimum cost for that sub-task, the heuristic is admissible.
    """
    def __init__(self, towers_gemini25pro_heuristic_11=1.0):
        super().__init__(name="TowersGemini25ProHeuristic11")
        self.weight = towers_gemini25pro_heuristic_11
        self.ring_sizes = {}
        self.total_rings = 0
        self.preprocessing_time = 0

    def initialize(self, model, initial_node):
        """
        Initializes the heuristic by pre-processing the domain to identify all
        rings and their corresponding sizes based on their names (e.g., 'r5' -> 5).
        """
        start_time = time.time()
        
        all_ring_names = set()
        if hasattr(model, 'facts'):
            for fact in model.facts:
                parts = fact.name.strip('()').split()
                for p in parts:
                    if p.startswith('r') and p[1:].isdigit():
                        all_ring_names.add(p)

        for ring_name in all_ring_names:
            try:
                size = int(ring_name[1:])
                self.ring_sizes[ring_name] = size
            except (ValueError, IndexError):
                pass

        self.total_rings = len(self.ring_sizes)
        self.preprocessing_time = time.time() - start_time
        
        initial_h_value = self._calculate_node_heuristic(initial_node)
        
        return super().initialize(model, initial_h_value)

    def _get_ring_size_from_params(self, params):
        """
        Finds the size of the largest ring mentioned in a method's parameters.
        This size 'k' is used as the size of the current subproblem.
        """
        max_size = 0
        for p in params:
            if p in self.ring_sizes:
                size = self.ring_sizes[p]
                if size > max_size:
                    max_size = size
        return max_size

    def _calculate_node_heuristic(self, node):
        """
        Calculates the heuristic value for a given search node based on the
        method it's trying to apply.
        """
        if not hasattr(node, 'method') or not node.method:
            return 0

        method = node.method
        method_base_name = method.name[0]
        params = list(method.name[1:])

        k = self._get_ring_size_from_params(params)
        
        h_value = 0.0

        if k > 0:
            if 'm-shiftTower' in method_base_name or 'selectedDirection' in method_base_name or 'm-selectDirection' in method_base_name:
                h_value = (2**k) - 1
            elif 'exchangeLR' in method_base_name or 'exchangeRL' in method_base_name:
                h_value = 2**(k - 1) if k > 1 else 1
        
        if h_value == 0:
            if 'newMethod21' in method_base_name:
                h_value = 1
            elif 'exchangeClear' in method_base_name:
                h_value = 0
            elif 'm-rotateTower' in method_base_name:
                h_value = 2
            else:
                h_value = 1

        return h_value * self.weight

    def __call__(self, parent_node, node):
        """
        The main entry point for the heuristic evaluation during search.
        """
        h_value = self._calculate_node_heuristic(node)
        super().update_info(h_value)
        return h_value

    def __repr__(self):
        return f"TowersGemini25ProHeuristic11(weight={self.weight})"

    def __str__(self):
        return self.__repr__()

    def __output__(self):
        return (
            f"Towers Gemini 2.5 Pro of Hanoi Heuristic 11 Info:\n"
            f"\tName: {self.name}\n"
            f"\tTotal Rings Detected: {self.total_rings}\n"
            f"\tWeight: {self.weight}\n"
            f"\tPreprocessing time: {self.preprocessing_time:.4f} s\n"
        )
