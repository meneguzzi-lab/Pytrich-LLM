import time
from collections import defaultdict
from Pytrich.Heuristics.heuristic import Heuristic
from Pytrich.Search.htn_node import HTNNode
from Pytrich.model import Model

"""
Domain-dependent heuristic for Blocksworld_GTOHP.

Analysis:
1. Bottleneck: The primary serialization in Blocksworld is clearing stacks and building new ones. 
   The HTN tasks (do_put_on, do_clear, do_move, do_on_table) map directly to sequences of 
   pick-up/unstack and stack/put-down actions.

2. Admissible Lower Bounds:
   - Term 1 (Task Network Work): Each grounded task in the current network requires a minimum 
     number of primitive actions based on the current state. For example, do_clear(x) requires 
     2 actions (unstack+put-down) for every block currently above x. 
   - Term 2 (State Penalty): If the hand is not empty, at least one action (stack or put-down) 
     is mandatory to proceed with handempty-required tasks.

Admissibility Sketch:
- Each estimate for a task (do_put_on, do_clear, etc.) is a lower bound on the number of primitive 
  actions (cost=1) generated by its decomposition tree. Since tasks are executed serially, 
  summing their minimum costs provides a lower bound on the total plan length.
"""

class BlocksworldGTOHPGemini3FlashHeuristic0(Heuristic):
    def __init__(self, blocksworld_gemini3flash_heuristic_0=None, name="BlocksworldGTOHPGemini3FlashHeuristic0"):
        super().__init__(name=name)
        self.on_ids = defaultdict(dict)  # x -> y -> global_id
        self.ontable_ids = {}            # x -> global_id
        self.holding_ids = {}            # x -> global_id
        self.fact_info = []              # idx -> (pred, args)
        self.preprocessing_time = 0

    def initialize(self, model: Model, initial_node: HTNNode):
        start_time = time.time()
        self.model = model
        self.fact_info = [None] * len(model.facts)

        for f in model.facts:
            info = self._parse_fact_name(f.name)
            self.fact_info[f.global_id] = info
            if info:
                pred, args = info
                if pred == "on" and len(args) == 2:
                    self.on_ids[args[0]][args[1]] = f.global_id
                elif pred == "ontable" and len(args) == 1:
                    self.ontable_ids[args[0]] = f.global_id
                elif pred == "holding" and len(args) == 1:
                    self.holding_ids[args[0]] = f.global_id

        self.preprocessing_time = time.time() - start_time
        h_value = self._compute(initial_node.state, initial_node.task_network)
        return super().initialize(model, h_value)

    def __call__(self, parent_node: HTNNode, node: HTNNode) -> int:
        h_value = self._compute(node.state, node.task_network)
        super().update_info(h_value)
        return h_value

    def _compute(self, state, task_network):
        if not task_network:
            return 0

        # 1. Build current world state maps
        on_top_of = {}  # y -> x (where x is on y)
        any_holding = False
        
        temp_state = state
        while temp_state:
            bit = temp_state & -temp_state
            idx = bit.bit_length() - 1
            temp_state ^= bit
            
            info = self.fact_info[idx]
            if info:
                pred, args = info
                if pred == "on":
                    on_top_of[args[1]] = args[0]
                elif pred == "holding":
                    any_holding = True

        # 2. Estimate cost for each task in the network
        h = 0
        for task in task_network:
            h += self._estimate_task_cost(task, state, on_top_of)

        if any_holding:
            h += 1

        # Sub-unit penalty to favor smaller task networks (guidance)
        h += int(0.01 * len(task_network))
        return h

    def _estimate_task_cost(self, task, state, on_top_of):
        name, args = self._parse_name_args(task.name)
        
        if name == 'do_put_on':
            x, y = args[0], args[1]
            # Method m0: already there
            on_id = self.on_ids.get(x, {}).get(y)
            if on_id is not None and (state >> on_id) & 1:
                return 0
            # Method m1: clear x, clear y, on_table y, move x y
            return 2 * self._count_above(x, on_top_of) + \
                   2 * self._count_above(y, on_top_of) + \
                   self._estimate_do_on_table(y, state) + 2
        
        elif name == 'do_clear':
            return 2 * self._count_above(args[0], on_top_of)
            
        elif name == 'do_on_table':
            return self._estimate_do_on_table(args[0], state)
            
        elif name == 'do_move':
            return 2
            
        elif name in ['pick-up', 'put-down', 'stack', 'unstack']:
            return 1
            
        return 0

    def _estimate_do_on_table(self, x, state):
        ot_id = self.ontable_ids.get(x)
        if ot_id is not None and (state >> ot_id) & 1:
            return 0
        return 2

    def _count_above(self, block, on_top_of):
        count = 0
        curr = block
        while curr in on_top_of:
            count += 1
            curr = on_top_of[curr]
            if count > 2000: break # cycle safety
        return count

    def _parse_name_args(self, name):
        parts = name.strip("() ").split()
        if not parts: return "", []
        return parts[0], parts[1:]

    def _parse_fact_name(self, name):
        name = name.strip()
        if name.startswith("+") or name.startswith("-"):
            name = name[1:]
            bracket_idx = name.find("[")
            if bracket_idx > 0 and name.endswith("]"):
                predicate = name[:bracket_idx]
                args_str = name[bracket_idx+1:-1]
                args = args_str.split(",") if args_str else []
                return predicate, args
        elif name.startswith("(") and name.endswith(")"):
            inner = name[1:-1]
            parts = inner.split()
            if parts: return parts[0], parts[1:]
        return None, []
